import { test, expect, type Page } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';

const EVIDENCE = 'docs/evidence/e2e';
mkdirSync(EVIDENCE, { recursive: true });

async function snap(page: Page, name: string) {
  const w = page.viewportSize()?.width ?? 0;
  await page.screenshot({ path: `${EVIDENCE}/${w}-${name}.png` });
}

function pngSize(path: string) {
  const b = readFileSync(path);
  expect(b.subarray(1, 4).toString()).toBe('PNG');
  return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) };
}

const DEVICE_SIZES: Record<string, [number, number]> = {
  'iphone-pro': [1206, 2622],
  'android-1080': [1080, 2400],
};

test('guest journey: goal → Gemini plan → edit/approve → countdown → studio → export → progress → offline', async ({
  page,
  context,
}) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));

  // 1 ─ Open as guest
  await page.goto('/');
  await expect(page.getByRole('heading', { name: /Your deadline/ })).toBeVisible();
  await page.evaluate(() => navigator.serviceWorker?.ready);
  await snap(page, '01-landing');

  // 2 ─ Goal + deadline + timezone
  await page.getByRole('button', { name: 'Lock in your deadline' }).first().click();
  await page.getByRole('textbox', { name: 'Your goal' }).fill('Pass the AWS Cloud Practitioner exam');
  await page.getByRole('button', { name: 'Continue' }).click();
  const deadline = new Date(Date.now() + 30 * 864e5).toISOString().slice(0, 10);
  await page.getByLabel('Deadline date').fill(deadline);
  await page.getByLabel('Time', { exact: true }).fill('10:00');
  await page.getByLabel('Time zone').fill('Europe/London');
  await expect(page.getByText(/days? from today/)).toBeVisible();
  await snap(page, '02-deadline');
  await page.getByRole('button', { name: 'Continue' }).click();

  // 3 ─ Hours + working days
  const slider = page.getByRole('slider', { name: 'Hours per working day' });
  await slider.focus();
  await page.keyboard.press('ArrowRight'); // 2.0 → 2.5 h
  await page.getByRole('button', { name: 'Saturday' }).click();
  await expect(page.getByText(/2\.5 h/).first()).toBeVisible();
  await snap(page, '03-time');
  await page.getByRole('button', { name: 'Continue' }).click();

  // 4 ─ Gemini plan passes all code checks
  await page.getByRole('button', { name: 'Plan with Gemini' }).click();
  await page.waitForURL(/\/plan$/);
  await snap(page, '04-planning');
  await page.waitForURL(/\/review$/, { timeout: 60_000 });
  await expect(page.getByText(/7\/7 code checks passed/)).toBeVisible();
  await expect(page.getByText('✦ AI suggestion').first()).toBeVisible();
  await expect(page.getByText(/Generated by Gemini \(gemini-e2e-mock\)/)).toBeVisible();
  await snap(page, '05-review');

  // 5 ─ Edit one milestone, approve
  await page.getByRole('button', { name: 'Edit Map the exam domains' }).click();
  await page.getByLabel('Title', { exact: true }).fill('Map the exam domains (my version)');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(page.getByText('Edited by you').first()).toBeVisible();
  await page.getByRole('button', { name: 'Approve plan' }).click();

  // 6 ─ Live countdown
  await page.waitForURL(/\/goals\/[^/]+$/);
  await expect(page.getByText(/days left · Day 1 of/i)).toBeVisible();
  const sr = page
    .locator('p[aria-live="polite"]', { hasText: /days, \d+ hours and \d+ minutes left/ })
    .first();
  await expect(sr).toBeAttached();
  await snap(page, '06-countdown');
  const goalUrl = page.url();

  // 7 ─ Studio + template
  await page.goto(goalUrl.replace('/goals/', '/studio/'));
  const preview = page.getByRole('img', { name: /Wallpaper preview:/ }).first();
  await expect(preview).toBeVisible();
  await page.getByRole('radio', { name: /Orbit/ }).first().click();
  // 8 ─ Preview shows real days left, next milestone, progress
  await expect(preview).toHaveAttribute(
    'aria-label',
    /\d+ days left, 0% done, next milestone Map the exam domains \(my version\)/,
  );
  await snap(page, '07-studio');

  // 9 ─ Export PNG at native resolution, dimensions verified
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  await expect(page.getByText(/1206 × 2622 px, checked from the PNG header/)).toBeVisible({
    timeout: 30_000,
  });
  await snap(page, '08-export');
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Download PNG' }).click(),
  ]);
  const file = test.info().outputPath(download.suggestedFilename());
  await download.saveAs(file);
  expect(download.suggestedFilename()).toMatch(
    /^lockstep-pass-the-aws-cloud-practitioner-exam-iphone-pro-\d{4}-\d{2}-\d{2}\.png$/,
  );
  expect(pngSize(file)).toEqual({
    width: DEVICE_SIZES['iphone-pro']![0],
    height: DEVICE_SIZES['iphone-pro']![1],
  });

  // 10 ─ Wallpaper guide
  await page.getByRole('button', { name: 'How to set it as your lock screen' }).click();
  await expect(page.getByText('Use as Wallpaper').first()).toBeVisible();
  await page.getByRole('tab', { name: /Android/ }).click();
  await expect(page.getByText(/Wallpaper & style/)).toBeVisible();
  await page.keyboard.press('Escape');

  // 11 ─ Complete tasks → progress updates
  await page.goto(goalUrl);
  // Checkboxes are controlled by IndexedDB, so click and then wait for the saved state.
  const taskA = page.locator('label', { hasText: 'Map the exam domains: part A' }).first();
  const taskB = page.locator('label', { hasText: 'Map the exam domains: part B' }).first();
  await taskA.click();
  await expect(taskA.getByRole('checkbox')).toBeChecked();
  await taskB.click();
  await expect(page.getByText('Milestone complete').first()).toBeVisible();
  await expect(taskB.getByRole('checkbox')).toBeChecked();
  await expect(page.getByText('Milestone complete').first()).toBeVisible();
  await expect(page.getByRole('img', { name: /Work done: [1-9]\d?%/ }).first()).toBeVisible();
  await snap(page, '09-progress');

  // 12 ─ Refresh wallpaper → reflects new progress
  await page.goto(goalUrl.replace('/goals/', '/studio/'));
  await page.getByRole('tab', { name: 'Export' }).click();
  await page.getByRole('button', { name: "Refresh with today's progress" }).first().click();
  await expect(page.getByRole('img', { name: /Wallpaper preview:/ }).first()).toHaveAttribute(
    'aria-label',
    /[1-9]\d?% done, next milestone Core services deep-dive/,
  );
  await snap(page, '10-refreshed');

  // 13 ─ Reload offline → data persists
  await context.setOffline(true);
  await page.goto(goalUrl);
  await expect(
    page.getByRole('heading', { name: 'Pass the AWS Cloud Practitioner exam' }).first(),
  ).toBeVisible();
  await snap(page, '11-offline');
  await context.setOffline(false);

  expect(errors, `page errors: ${errors.join(' | ')}`).toEqual([]);
});

